import express from 'express'
import { auth, getAccessLevel } from '../middleware/authorisation.js'
import { verifyResourceData, verifyResourceEditData } from '../middleware/data-verification.js'
import { generateUploadURL, generateDownloadURL, deleteResourceFromS3 } from '../services/s3Service.js'

const router = express.Router()

/**
 * The endpoint at which a new resource can be added
 */
router.post('/create', auth, verifyResourceData, getAccessLevel, async (req, res, next) => {
    // Recieve metadata after verification
    const { type, title, extension, mimeType, parentID, accessLevel } = req.body;

    let currentDate = new Date();

    if (req.accessTo.includes('ranger')) {
        res.status(403).json({
            error: true,
            message: "Current user is not authorised to add a resource. Only rangers and higher roles can add resources."
        });
        return;
    }

    // Verify the user isn't attempting to give the resource an accessLevel higher than their own
    if (!req.accessTo.includes(req.body.accessLevel)) {
        res.status(403).json({ error: true, message: "User does not have permission to add resource with specified access level" });
        return;
    }

    // Create resource row with metadata
    const uploaderID = req.user_id;
    
    try {
        // ResourceID will be generated by the database upon insertion, and we will use that to generate the presigned URL for S3 upload.
        const [resourceID] = await req.db.from("resource").insert({
            type: type.toLowerCase(), // Ensure type is stored in lowercase for consistency
            title,
            uploader_id: uploaderID,
            extension: extension,
            mime_type: mimeType,
            parent_id: parentID,
            access_level: accessLevel.toLowerCase(), // Ensure access level is stored in lowercase for consistency
            status: 'pending', // New resources are pending until the file is uploaded and verified TODO: Add handling for when files fail to upload or are rejected.
            created: currentDate.toISOString().slice(0, 19).replace('T', ' '), // Convert time to MySQL DATETIME format
        });
        // Generate presigned URL for file upload to S3 bucket
        const uploadURL = await generateUploadURL(`resource-hub/${resourceID}`, mimeType);

        res.status(201).json({ message: "Resource metadata added successfully", resourceID: resourceID, uploadURL: uploadURL }) // Pass presigned URL back to the client for file upload
    }
    catch (e) {
        console.log(e.message)
        res.status(500).json({ error: true, message: "Failed to create resource" })
    }    
})

/**
 * The endpoint at which a resource's status can be updated to 'success' after the file upload is complete
 */
router.put('/:resourceID/complete', auth, async (req, res, next) => {
    const resourceID = Number.parseInt(req.params.resourceID, 10);
    if (Number.isNaN(resourceID))
    {
        res.status(400).json({
            error: true,
            message: "Resource ID is invalid"
        });
        return;
    }

    // Update resource status to 'success' after file upload is complete
    try {
        const result = await req.db.from("resource").where('resource_id', resourceID).update({ status: 'success' });
    }
    catch (e) {
        console.log(e.message)
        res.status(500).json({ error: true, message: "Failed to update resource status" })
    }
})        

/**
 * The endpoint at which a resource's information can be updated
 */
router.put('/:resourceID/edit', auth, getAccessLevel, verifyResourceEditData, async (req, res, next) => {
    const resourceID = Number.parseInt(req.params.resourceID, 10);
    if (Number.isNaN(resourceID))
    {
        res.status(400).json({
            error: true,
            message: "Resource ID is invalid"
        });
        return;
    }

    console.log('Attempting to edit resource with ID:', resourceID);

    const fields = ['title', 'access_level', 'uploader_id'];

    const current_resource = await req.db.from("resource").select(fields).where('resource_id', resourceID).first();

    // Check user has permissions to update this resource
    if (!req.accessTo.includes(current_resource.access_level)) {
        res.status(403).json({ error: true, message: "User does not have permission to update this resource" });
        return;
    }

    // Verify the user isn't attempting to give the resource an accessLevel higher than their own
    if (req.body.accessLevel && !req.accessTo.includes(req.body.accessLevel)) {
        res.status(403).json({ error: true, message: "User does not have permission to update resource with specified access level" });
        return;
    }

    if (current_resource.uploader_id !== req.user_id && !req.accessTo.includes('admin')) {
        res.status(403).json({ error: true, message: "User does not have permission to update this resource" });
        return;
    }

    // Update resource information
    try {
        const { title, accessLevel } = req.body;
        const result = await req.db.from("resource").where('resource_id', resourceID).update({
            title: title || current_resource.title,
            access_level: accessLevel || current_resource.access_level
        });
        res.json({ message: "Resource updated successfully" });
    }
    catch (e) {
        console.log(e.message)
        res.status(500).json({ error: true, message: "Failed to update resource" })
    }
})

/**
 * The endpoint at which a resource's information can be retrieved
 */
router.get('/:resourceID', auth, getAccessLevel, (req, res, next) => {
    const resourceID = Number.parseInt(req.params.resourceID, 10);
    if (Number.isNaN(resourceID))
    {
        res.status(400).json({
            error: true,
            message: "Resource ID is invalid"
        });
        return;
    }

    let fields = ['type', 'title', 'uploader_id', 'extension', 'mime_type', 'parent_id', 'access_level', 'created']

    let accessTo = req.accessTo;

    req.db.from("resource")
    .select(fields)
    .where('resource_id', resourceID)
    .first() // There should only ever be one resource with a given resourceID
    .then(resource => {
        if (!resource) {
            res.status(404).json({ error: true, message: "Resource not found" });
            return;
        }
        if (!accessTo.includes(resource.access_level)) {
            res.status(403).json({ error: true, message: "User does not have access to view this resource"});
            return;
        }

        const data = {
            id: resourceID,
            type: resource.type,
            title: resource.title,
            uploaderID: resource.uploader_id,
            extension: resource.extension,
            mimeType: resource.mime_type,
            parentID: resource.parent_id,
            accessLevel: resource.access_level,
            created: resource.created
        }
        res.json(data)
    })
    .catch((e) => {
      console.log(e.message)
      res.status(500).json({ error: true })
    })
})

/**
 * The endpoint at which a resource's download URL can be retrieved. This URL is a presigned URL that allows the user to download the resource file directly from S3.
 * The presigned URL is valid for a limited time (5 minutes) and can be used to download the resource file without requiring further authentication.
 * The resource's access level is checked to ensure that the user has permission to download the resource.
 */
router.get('/:resourceID/download', auth, getAccessLevel, async (req, res, next) => {
    const resourceID = Number.parseInt(req.params.resourceID, 10);
    if (Number.isNaN(resourceID))
    {
        res.status(400).json({
            error: true,
            message: "Resource ID is invalid"
        });
        return;
    }

    // Retrieve resource information
    try {
        const resource = await req.db.from("resource").where('resource_id', resourceID).first();
        if (!resource) {
            res.status(404).json({ error: true, message: "Resource not found" });
            return;
        }
        if (!req.accessTo.includes(resource.access_level)) {
            res.status(403).json({ error: true, message: "User does not have access to download this resource"});
            return;
        }

        // Generate presigned download URL
        const downloadURL = await generateDownloadURL(`resource-hub/${resourceID}`, resource.title, resource.extension, resource.mime_type);
        res.json({ downloadURL });
    } catch (e) {
        console.error("Error generating download URL:", e);
        res.status(500).json({ error: true, message: "Failed to generate download URL" });
    }
});

